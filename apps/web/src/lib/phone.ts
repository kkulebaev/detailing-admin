// Показывает хранимый E.164-телефон (`+7XXXXXXXXXX`) как `+7-XXX-XXX-XX-XX` для
// отображения — общий для всех страниц со списками телефонов клиентов (записи,
// аналитика), чтобы группировку не переписывали в каждом компоненте. Возвращает
// вход без изменений, если он не оканчивается ожидаемым 10-значным хвостом.
export function formatPhone(raw: string): string {
  const match = /^(.+?)(\d{3})(\d{3})(\d{2})(\d{2})$/.exec(raw)
  if (!match) return raw
  const [, prefix, a, b, c, d] = match
  return `${prefix}-${a}-${b}-${c}-${d}`
}
